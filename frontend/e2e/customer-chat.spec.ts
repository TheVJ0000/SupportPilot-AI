test.describe('human handoff', () => {
  test.use({ scenario: 'insufficient' })
  test('insufficient evidence, confirmed human request and paused AI', async ({ page }) => {
    await page.goto(`/chat/${PUBLIC}`)
    await send(page)
    await expect(page.getByRole('button', { name: 'Mark this answer as helpful', exact: true })).toBeVisible()
    await expect(page.getByText("I don't have enough information in the available knowledge base to answer that reliably.", { exact: true })).toBeVisible()
    await expect(page.getByRole('listitem').filter({ hasText: 'Shipping Policy' })).toHaveCount(0)
    await expect(page.getByLabel('Assistant response in progress')).toHaveCount(0)
    await page.getByRole('button', { name: 'Request a human', exact: true }).first().click()
    await page.getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page.getByText('A human support request has been recorded.')).toBeVisible()
    await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Request a human', exact: true })).toHaveCount(0)
    await page.reload()
    await expect(page.getByText('AI messaging is paused for this conversation.')).toBeVisible()
  })
})

test('closed conversation history is readable and sending disabled', async ({ page, request, release }) => {
  await page.goto(`/chat/${PUBLIC}`)
  await send(page)
  await finish(page, release)
  expect((await request.post(`${API}/_e2e/close`)).ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByText('Orders ship within two days.', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await expect(page.getByRole('status')).toContainText('This conversation is closed.')
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toHaveAttribute('placeholder', 'This conversation is not accepting new messages.')
})

